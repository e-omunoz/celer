// The test data generator (#172) in the desktop app (dev/run-desktop.ps1 -Slot n), on a PostgreSQL connection
// (CONN, default "PostgreSQL" as dev/devdata-connections.mjs names it): the dialog from the explorer's table menu,
// the proposed generators, the preview, 3,000 rows inserted and checked by SQL, Cancelar rolling a big run back, the
// script output in a new console and an empty referenced table offered to be filled first.
//   CDP_PORT=9334 CONN=PostgreSQL node dev/testdata-e2e-check.mjs
import { connect } from "./cdp-lib.mjs";

const CONN = process.env.CONN || "PostgreSQL";
const app = await connect(process.env.CDP_PORT || 9333);
const H = `
  const CONN = ${JSON.stringify(CONN)};
  const rowByText = (text) => [...document.querySelectorAll('.tree-row')].find((e) => e.querySelector('.tree-name')?.textContent === text);
  const menuItem = (re) => until(() => [...document.querySelectorAll('.menu .menu-item')].find((b) => re.test(b.textContent)), 3000);
  const td = () => document.querySelector('.testdata-dialog');
  const setInput = (el, value) => { el.value = String(value); el.dispatchEvent(new Event('input', { bubbles: true })); };
  const q = async (text) => (await sql(CONN, text)).results[0]?.rows ?? [];
  const openOn = async (table) => {
    if (td()) { button(/^Cerrar$/, td())?.click(); await until(() => !td(), 3000); }
    const row = await until(() => rowByText(table), 8000);
    if (!row) return false;
    const r = row.getBoundingClientRect();
    row.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: r.left + 40, clientY: r.top + 8 }));
    (await menuItem(/^Generar datos de prueba/))?.click();
    return !!(await until(() => td()?.querySelector('.td-map'), 20000));
  };
  const generators = () => Object.fromEntries([...td().querySelectorAll('.td-item')].map((item) => [item.querySelector('.td-col b').textContent, item.querySelector('select').value]));
`;
const js = (code) => app.js(H + code, { helpers: true });
let failed = 0;
const check = (name, ok, detail = "") => {
  console.log(`${ok ? "ok  " : "FAIL"} ${name}${ok ? "" : ` — ${String(detail).slice(0, 500)}`}`);
  if (!ok) failed++;
};

await js(`await until(() => document.querySelector('.app.ready') && !document.querySelector('.splash'), 20000);`);
await js(`
  await q("DROP TABLE IF EXISTS celer_td_e2e_child, celer_td_e2e_parent, celer_td_e2e_orphan, celer_td_e2e_empty; DROP TYPE IF EXISTS celer_td_e2e_estado");
  await q("CREATE TYPE celer_td_e2e_estado AS ENUM ('nuevo', 'enviado', 'entregado')");
  await q("CREATE TABLE celer_td_e2e_parent (id INT PRIMARY KEY, nombre VARCHAR(60) NOT NULL)");
  await q("INSERT INTO celer_td_e2e_parent SELECT g, 'Padre ' || g FROM generate_series(1, 20) g");
  await q("CREATE TABLE celer_td_e2e_child (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo VARCHAR(12) NOT NULL UNIQUE, nombre VARCHAR(40) NOT NULL, apellidos VARCHAR(60), email VARCHAR(120) UNIQUE, parent_id INT NOT NULL REFERENCES celer_td_e2e_parent(id), estado celer_td_e2e_estado NOT NULL, prioridad VARCHAR(10) NOT NULL CHECK (prioridad IN ('baja', 'media', 'alta')), puntos INT CHECK (puntos BETWEEN 0 AND 100), alta DATE NOT NULL, importe NUMERIC(10,2) NOT NULL, activo BOOLEAN NOT NULL, foto BYTEA)");
  await q("CREATE TABLE celer_td_e2e_empty (id INT PRIMARY KEY)");
  await q("CREATE TABLE celer_td_e2e_orphan (id SERIAL PRIMARY KEY, empty_id INT NOT NULL REFERENCES celer_td_e2e_empty(id))");
  const conn = await findConn(CONN);
  if (!conn.classList.contains('connected')) { conn.dispatchEvent(new MouseEvent('dblclick', { bubbles: true })); await until(() => connRow(CONN)?.classList.contains('connected'), 30000); }
  await menu(CONN, /^Actualizar/);
  await until(() => rowByText('celer_td_e2e_child'), 15000);
`);

// ---------------------------------------------------------------- the dialog and its proposals
const proposed = await js(`
  if (!(await openOn('celer_td_e2e_child'))) return { error: 'no dialog' };
  return generators();
`);
check("dialog opens from the table's menu", !proposed.error, JSON.stringify(proposed));
check(
  "generators inferred from type, name and constraints",
  proposed.id === "skip" && proposed.codigo === "pattern" && proposed.nombre === "firstName" && proposed.email === "expression" && proposed.parent_id === "fk" && proposed.estado === "list" && proposed.prioridad === "list" && proposed.puntos === "integer" && proposed.alta === "date" && proposed.activo === "boolean" && proposed.foto === "binary",
  JSON.stringify(proposed),
);
const preview = await js(`
  button(/^Vista previa/, td()).click();
  await until(() => td().querySelector('.td-preview tbody tr'), 3000);
  const rows = td().querySelectorAll('.td-preview tbody tr').length;
  const heads = [...td().querySelectorAll('.td-preview th')].map((th) => th.textContent);
  button(/^Columnas$/, td()).click();
  return { rows, heads };
`);
check("preview shows 20 rows without the identity column", preview.rows === 20 && !preview.heads.includes("id") && preview.heads.includes("codigo"), JSON.stringify(preview));

// ---------------------------------------------------------------- 3,000 rows inserted
const inserted = await js(`
  setInput(td().querySelector('.td-count input'), 3000);
  await sleep(200);
  const label = td().querySelector('footer .btn.primary').textContent;
  td().querySelector('footer .btn.primary').click();
  await until(() => !td(), 60000);
  await sleep(300);
  return { label, toasts: toasts(), count: (await q("SELECT COUNT(*) FROM celer_td_e2e_child"))[0][0], orphans: (await q("SELECT COUNT(*) FROM celer_td_e2e_child c LEFT JOIN celer_td_e2e_parent p ON p.id = c.parent_id WHERE p.id IS NULL"))[0][0], dup: (await q("SELECT COUNT(*) FROM (SELECT email FROM celer_td_e2e_child WHERE email IS NOT NULL GROUP BY email HAVING COUNT(*) > 1) d"))[0][0] };
`);
check("«Insertar 3.000 filas» inserts them all", /3\.000/.test(inserted.label) && Number(inserted.count) === 3000, JSON.stringify(inserted));
check("foreign keys only take parent keys, unique e-mails", Number(inserted.orphans) === 0 && Number(inserted.dup) === 0, JSON.stringify(inserted));
check("success toast", inserted.toasts.some((t) => /Insertadas 3\.000 filas/.test(t.text)), JSON.stringify(inserted.toasts));

// ---------------------------------------------------------------- Cancelar rolls a big run back
const cancelled = await js(`
  if (!(await openOn('celer_td_e2e_child'))) return { error: 'no dialog' };
  setInput(td().querySelector('.td-count input'), 300000);
  await sleep(200);
  td().querySelector('footer .btn.primary').click();
  const progress = await until(() => { const b = td()?.querySelector('.export-progress b'); return b && Number(b.textContent.replace(/\\D/g, '')) > 0 ? b.textContent : null; }, 30000);
  const started = Date.now();
  button(/^Cancelar$/, td()).click();
  await until(() => !td()?.querySelector('.export-progress'), 30000);
  const stoppedMs = Date.now() - started;
  await sleep(300);
  return { progress, stoppedMs, toasts: toasts(), count: (await q("SELECT COUNT(*) FROM celer_td_e2e_child"))[0][0] };
`);
check("progress while inserting", Boolean(cancelled.progress), JSON.stringify(cancelled));
check("Cancelar stops quickly and rolls back everything", Number(cancelled.count) === 3000 && cancelled.stoppedMs < 10000, JSON.stringify(cancelled));

// ---------------------------------------------------------------- the script output
const script = await js(`
  const before = document.querySelectorAll('.tab').length;
  button(/^Script SQL$/, td()).click();
  setInput(td().querySelector('.td-count input'), 50);
  await sleep(200);
  td().querySelector('footer .btn.primary').click();
  await until(() => !td() && document.querySelectorAll('.tab').length > before, 10000);
  await sleep(500);
  const text = view()?.state.doc.toString() ?? '';
  return { tabs: tabs(), inserts: (text.match(/INSERT INTO/g) || []).length, head: text.slice(0, 120), count: (await q("SELECT COUNT(*) FROM celer_td_e2e_child"))[0][0] };
`);
check("script opens in a new console, nothing run", script.inserts === 1 && /Datos de prueba/.test(script.head) && Number(script.count) === 3000, JSON.stringify(script));
await js(`closeActive(); await sleep(300); const d = dialog(); if (d) button(/No guardar|Descartar|Cerrar sin/, d)?.click();`);

// ---------------------------------------------------------------- an empty referenced table
const empty = await js(`
  if (!(await openOn('celer_td_e2e_orphan'))) return { error: 'no dialog' };
  const problem = [...td().querySelectorAll('.td-problem')].map((p) => p.textContent).join(' | ');
  const offer = button(/^Generar antes datos de celer_td_e2e_empty/, td());
  const disabled = td().querySelector('footer .btn.primary').disabled;
  offer?.click();
  await until(() => /celer_td_e2e_empty/.test(td()?.querySelector('h2')?.textContent ?? ''), 15000);
  const title = td()?.querySelector('h2')?.textContent;
  button(/^Cerrar$/, td())?.click();
  return { problem, offer: !!offer, disabled, title };
`);
check("empty parent: a clear message, no insert, an offer to fill it first", /está vacía/.test(empty.problem ?? "") && empty.offer && empty.disabled && /celer_td_e2e_empty/.test(empty.title ?? ""), JSON.stringify(empty));

await js(`await q("DROP TABLE IF EXISTS celer_td_e2e_child, celer_td_e2e_parent, celer_td_e2e_orphan, celer_td_e2e_empty; DROP TYPE IF EXISTS celer_td_e2e_estado");`);
app.close?.();
if (failed) {
  console.log(`${failed} check(s) failed`);
  process.exit(1);
}
console.log("testdata-e2e-check: all good");
