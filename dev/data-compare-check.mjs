// Comparing the rows of two tables against "Postgres local" in the desktop app (dev/run-desktop.ps1): one table
// marked and the other compared with it from the explorer; the sync script is opened, run, and a second
// comparison leaves only the row it deliberately does not delete.
import { connect, sleep } from "./cdp-lib.mjs";

const app = await connect(process.env.CDP_PORT || 9333);
const H = `
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const until = async (fn, ms = 15000) => { const t = Date.now(); while (Date.now() - t < ms) { const v = fn(); if (v) return v; await sleep(50); } return null; };
  const inv = (cmd, args) => window.__TAURI_INTERNALS__.invoke(cmd, args);
  const rowByText = (text) => [...document.querySelectorAll('.tree-row')].find((e) => e.querySelector('.tree-name')?.textContent === text);
  const connRow = () => [...document.querySelectorAll('.tree-row.conn')].find((e) => e.textContent.includes('Postgres local'));
  const menuItem = (re) => until(() => [...document.querySelectorAll('.menu .menu-item')].find((b) => re.test(b.textContent)), 3000);
  const menuOn = async (row, re) => { row.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 140, clientY: 200 })); const item = await menuItem(re); const label = item?.textContent ?? ''; item?.click(); return label; };
  const pane = () => document.querySelector('.pane-host.active');
  const sql = async (text) => {
    const c = (await inv('list_connections')).find((x) => x.name === 'Postgres local');
    const s = await inv('open_session', { connId: c.id, password: null });
    try { return await inv('execute', { sessionId: s.sessionId, sql: text, fetch: 100 }); } finally { await inv('close_session', { sessionId: s.sessionId }); }
  };
  const report = () => {
    const d = document.querySelector('.data-compare');
    if (!d) return null;
    return { loading: !!d.querySelector('.sc-progress'), error: d.querySelector('.import-warn')?.textContent ?? '', chips: [...d.querySelectorAll('.compare-chip')].map((c) => c.textContent), key: d.querySelector('.dc-head .muted')?.textContent ?? '', sides: [...d.querySelectorAll('.sc-side b')].map((b) => b.textContent) };
  };
`;
const js = (code) => app.js(H + code);
let failed = 0;
const check = (name, ok, detail = "") => {
  console.log(`${ok ? "ok  " : "FAIL"} ${name}${ok ? "" : ` — ${String(detail).slice(0, 500)}`}`);
  if (!ok) failed++;
};
async function press(key, mods = 0) {
  const vk = { Enter: 13, Escape: 27 }[key] ?? key.toUpperCase().charCodeAt(0);
  await app.send("Input.dispatchKeyEvent", { type: "rawKeyDown", key, code: key.length === 1 ? `Key${key.toUpperCase()}` : key, windowsVirtualKeyCode: vk, modifiers: mods });
  await app.send("Input.dispatchKeyEvent", { type: "keyUp", key, code: key.length === 1 ? `Key${key.toUpperCase()}` : key, windowsVirtualKeyCode: vk, modifiers: mods });
}

await js(`await until(() => document.querySelector('.app.ready') && !document.querySelector('.splash'), 20000);`);
if (await js(`return !!document.querySelector('.onboarding');`)) await press("Escape");
await js(`
  await sql("DROP TABLE IF EXISTS dc_a; DROP TABLE IF EXISTS dc_b; " +
    "CREATE TABLE dc_a (id int PRIMARY KEY, nombre text, activo boolean, alta date); CREATE TABLE dc_b (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text, activo boolean, alta date); " +
    "INSERT INTO dc_a VALUES (1, 'Ana', true, '2024-01-01'), (2, 'Luis', false, '2024-02-02'), (4, 'O''Neil', NULL, NULL); " +
    "INSERT INTO dc_b VALUES (1, 'Ana', true, '2024-01-01'), (2, 'Luís', true, '2024-02-02'), (3, 'Viejo', true, NULL)");
  if (!connRow().classList.contains('connected')) { connRow().dispatchEvent(new MouseEvent('dblclick', { bubbles: true })); await until(() => connRow().classList.contains('connected')); }
  await until(() => rowByText('public'));
  await menuOn(connRow(), /^Actualizar/);
  await until(() => rowByText('dc_a') && rowByText('dc_b'));
`);
const marked = await js(`return await menuOn(rowByText('dc_a'), /^Marca(r|da) para comparar datos/);`);
check("a table can be marked for a data comparison", /comparar datos/.test(marked), marked);
const offered = await js(`return await menuOn(rowByText('dc_b'), /^Comparar datos con/);`);
check("another table offers 'Comparar datos con' the marked one", /Comparar datos con «Postgres local · celer · public · dc_a»/.test(offered), offered);
const first = await js(`await until(() => { const r = report(); return r && !r.loading; }, 20000); await sleep(300); return report();`);
check("counts: equal, changed, only in source, only in target", JSON.stringify(first?.chips) === JSON.stringify(["1 iguales", "1 cambiadas", "1 solo en el origen", "1 solo en el destino"]), JSON.stringify(first));
check("rows matched by the primary key", /emparejadas por id/.test(first?.key ?? ""), first?.key);
const script = await js(`
  const before = document.querySelectorAll('.tab').length;
  [...document.querySelectorAll('.data-compare footer button')].find((b) => /Script para igualar/.test(b.textContent)).click();
  await until(() => document.querySelectorAll('.tab').length > before && !document.querySelector('.data-compare'));
  await sleep(500);
  return [...pane().querySelectorAll('.cm-line')].map((l) => l.textContent).join('\\n');
`);
check("the script inserts the missing row (identity value kept)", /INSERT INTO "public"\."dc_b" \("id", "nombre", "activo", "alta"\) OVERRIDING SYSTEM VALUE VALUES \(4, 'O''Neil', NULL, NULL\);/.test(script), script);
check("updates only the changed columns", /UPDATE "public"\."dc_b" SET "nombre" = 'Luis', "activo" = FALSE WHERE "id" = 2;/.test(script), script);
check("leaves the delete commented", /^-- DELETE FROM "public"\."dc_b" WHERE "id" = 3;$/m.test(script), script);
await js(`pane().querySelector('.cm-content').focus();`);
await press("Enter", 2 | 8);
await js(`await sleep(300); await until(() => !pane().querySelector('.progress-bar') && !pane().querySelector('.tb-btn.stop'), 20000); await sleep(400);`);
const second = await js(`
  await menuOn(rowByText('dc_b'), /^Comparar datos con/);
  await until(() => { const r = report(); return r && !r.loading; }, 20000); await sleep(200);
  const r = report();
  document.querySelector('.data-compare footer .btn:not(.primary)').click();
  return r;
`);
check("after running it, only the row it does not delete differs", JSON.stringify(second?.chips) === JSON.stringify(["3 iguales", "0 cambiadas", "0 solo en el origen", "1 solo en el destino"]), JSON.stringify(second));
const rows = await js(`return (await sql("SELECT id, nombre, activo FROM dc_b ORDER BY id")).results[0].rows;`);
check("the target holds the source's rows (and its own extra one)", JSON.stringify(rows) === JSON.stringify([[1, "Ana", true], [2, "Luis", false], [3, "Viejo", true], [4, "O'Neil", null]]), JSON.stringify(rows));
await js(`await sql("DROP TABLE IF EXISTS dc_a; DROP TABLE IF EXISTS dc_b"); await menuOn(connRow(), /^Actualizar/);`);
app.close?.();
if (failed) {
  console.log(`${failed} check(s) failed`);
  process.exit(1);
}
console.log("data-compare-check: all good");
